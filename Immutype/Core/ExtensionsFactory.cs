namespace Immutype.Core;

#if ROSLYN38
using NamespaceType = NamespaceDeclarationSyntax;
#else
using NamespaceType = BaseNamespaceDeclarationSyntax;
#endif

internal sealed class ExtensionsFactory(
    IMethodsFactory methodsFactory,
    IInformation information,
    IComments comments) : IUnitFactory
{
    public IEnumerable<Source> Create(GenerationContext<TypeDeclarationSyntax> context, IReadOnlyList<ParameterSyntax> parameters)
    {
        var type = context.Syntax;
        var namespaces = type.Ancestors().OfType<NamespaceType>().Reverse().ToArray();
        var namespaceName = string.Join(".", namespaces.Select(ns => ns.Name.ToString()));
        var name = type.Identifier.Text;
        var qualifiedName = namespaceName.Length > 0 ? $"{namespaceName}.{name}" : name;
        context = context with { DocComments = comments.GetParamsComments(type.DescendantTrivia()) };

        var code = new LineBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine($"// by {information.Description}");
        code.AppendLine("#pragma warning disable");
        if (context.Compilation.Options.NullableContextOptions != NullableContextOptions.Disable)
        {
            code.AppendLine("#nullable enable");
        }

        if (type.SyntaxTree.GetRoot(context.CancellationToken) is CompilationUnitSyntax root)
        {
            WriteImports(code, root.Externs, root.Usings);
        }

        WriteNamespace(0);
        code.AppendLine("#pragma warning restore");
        yield return new Source($"{qualifiedName}.g", SourceText.From(code.ToString(), Encoding.UTF8));
        yield break;

        void WriteNamespace(int depth)
        {
            if (depth == namespaces.Length)
            {
                WriteExtensions(code, context, parameters, $"global::{qualifiedName}");
                return;
            }

            var ns = namespaces[depth];
            code.AppendLine($"namespace {ns.Name}");
            using (code.Block())
            {
                WriteImports(code, ns.Externs, ns.Usings);
                WriteNamespace(depth + 1);
            }
        }
    }

    private void WriteExtensions(
        LineBuilder code,
        GenerationContext<TypeDeclarationSyntax> context,
        IReadOnlyList<ParameterSyntax> parameters,
        string targetType)
    {
        if (context.Compilation.GetTypeByMetadataName("System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute") != null)
        {
            code.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        }

        var modifiers = string.Concat(context.Syntax.Modifiers
            .Where(modifier => modifier.Kind() is SyntaxKind.PublicKeyword or SyntaxKind.InternalKeyword or SyntaxKind.UnsafeKeyword)
            .Select(modifier => modifier.Text + " "));
        code.AppendLine($"{modifiers}static partial class {context.Syntax.Identifier.ValueText}Extensions");
        using (code.Block())
        {
            methodsFactory.Build(code, context, targetType, parameters);
        }
    }

    private static void WriteImports(LineBuilder code, SyntaxList<ExternAliasDirectiveSyntax> externs, SyntaxList<UsingDirectiveSyntax> usings)
    {
        foreach (var alias in externs)
        {
            code.AppendLine(alias.ToString());
        }

        foreach (var directive in usings.Where(directive => directive.GetFirstToken().IsKind(SyntaxKind.UsingKeyword)))
        {
            code.AppendLine(directive.ToString());
        }
    }
}
